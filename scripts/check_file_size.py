#!/usr/bin/env python3
"""
Guard: file-size and folder-size limits (standards D10).

Rules (frontend/src: .ts/.tsx, huf/: .py):
  * a NEW file over 500 lines fails
  * a file recorded in the baseline may not grow
  * a NEW services/*Api.ts over 600 lines fails
  * a directory with more than 15 source files fails if it is new or grew
    beyond its baseline count
  * files over 300 lines only print a warning

The baseline (scripts/baselines/file_size.json) only ever shrinks.

Usage:
    python3 scripts/check_file_size.py            # check
    python3 scripts/check_file_size.py --list     # offenders, largest first
    python3 scripts/check_file_size.py --update   # rewrite baseline (decreases only)
    python3 scripts/check_file_size.py --update --force   # allow increases
"""

import argparse
import json
import sys
from pathlib import Path

HARD_LIMIT = 500
WARN_LIMIT = 300
API_LIMIT = 600
FOLDER_LIMIT = 15

SCAN = [
    ("frontend/src", {".ts", ".tsx"}),
    ("huf", {".py"}),
]
SKIP_DIRS = {
    "node_modules", "__pycache__", "migrations", "patches", "tests", "test", "__tests__",
    "fixtures", "generated", "__generated__", "dist", "public", "locale",
}
SKIP_SUFFIXES = ("_test.py", ".d.ts", ".test.ts", ".test.tsx", ".spec.ts", ".spec.tsx", ".generated.ts")

DEFAULT_BASELINE = Path(__file__).resolve().parent / "baselines" / "file_size.json"


def line_count(path: Path) -> int:
    with open(path, "rb") as fh:
        return sum(1 for _ in fh)


def scan(root: Path):
    """Return ({relpath: lines}, {reldir: source file count})."""
    files, folders = {}, {}
    for base, exts in SCAN:
        top = root / base
        if not top.is_dir():
            continue
        for p in top.rglob("*"):
            if (not p.is_file() or p.suffix not in exts or p.name.endswith(SKIP_SUFFIXES)
                    or p.name.startswith("test_")):
                continue
            rel = p.relative_to(root)
            if any(part in SKIP_DIRS for part in rel.parts[:-1]):
                continue
            files[rel.as_posix()] = line_count(p)
            folders[rel.parent.as_posix()] = folders.get(rel.parent.as_posix(), 0) + 1
    return files, folders


def is_api(rel: str) -> bool:
    parts = rel.split("/")
    return len(parts) >= 2 and parts[-2] == "services" and parts[-1].endswith("Api.ts")


def load_baseline(path: Path):
    if not path.exists():
        return None
    data = json.loads(path.read_text())
    return data.get("files", {}), data.get("folders", {})


def build_baseline(files, folders):
    return {
        "_comment": "Generated by scripts/check_file_size.py --update. Entries may only shrink or disappear.",
        "files": {k: v for k, v in sorted(files.items()) if v > HARD_LIMIT},
        "folders": {k: v for k, v in sorted(folders.items()) if v > FOLDER_LIMIT},
    }


def check(files, folders, base_files, base_folders):
    errors, warnings, stale = [], [], []
    for rel, n in sorted(files.items()):
        if rel in base_files:
            if n > base_files[rel]:
                errors.append(f"{rel}: {n} lines, grew past baseline {base_files[rel]}")
            elif n <= HARD_LIMIT:
                stale.append(rel)
            continue
        if is_api(rel) and n > API_LIMIT:
            errors.append(f"{rel}: new service API file has {n} lines (limit {API_LIMIT})")
        elif n > HARD_LIMIT:
            errors.append(f"{rel}: new file has {n} lines (limit {HARD_LIMIT})")
        elif n > WARN_LIMIT:
            warnings.append(f"{rel}: {n} lines (over {WARN_LIMIT}, consider splitting)")
    for rel, n in sorted(files.items()):
        if rel in base_files and WARN_LIMIT < n <= HARD_LIMIT:
            warnings.append(f"{rel}: {n} lines (over {WARN_LIMIT}, consider splitting)")
    for d, n in sorted(folders.items()):
        if n <= FOLDER_LIMIT:
            continue
        if d not in base_folders:
            errors.append(f"{d}/: {n} source files (limit {FOLDER_LIMIT}), new folder over limit")
        elif n > base_folders[d]:
            errors.append(f"{d}/: {n} source files, grew past baseline {base_folders[d]}")
    return errors, warnings, stale


def increases(old, new):
    """Entries in `new` that are new or larger than in `old`."""
    out = []
    for kind in ("files", "folders"):
        for k, v in new[kind].items():
            if k not in old[kind] or v > old[kind][k]:
                out.append(f"{kind[:-1]} {k}: {old[kind].get(k, 'absent')} -> {v}")
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--list", action="store_true", help="list offenders sorted by size")
    ap.add_argument("--update", action="store_true", help="rewrite baseline (decreases only)")
    ap.add_argument("--force", action="store_true", help="with --update, allow increases")
    ap.add_argument("-v", "--verbose", action="store_true", help="print every >300 line warning")
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    ap.add_argument("--baseline", type=Path, default=DEFAULT_BASELINE)
    args = ap.parse_args(argv)

    files, folders = scan(args.root)

    if args.list:
        print("Files over %d lines:" % WARN_LIMIT)
        for rel, n in sorted(files.items(), key=lambda kv: (-kv[1], kv[0])):
            if n > WARN_LIMIT:
                print(f"  {n:6d}  {rel}")
        print("Folders over %d source files:" % FOLDER_LIMIT)
        for d, n in sorted(folders.items(), key=lambda kv: (-kv[1], kv[0])):
            if n > FOLDER_LIMIT:
                print(f"  {n:6d}  {d}/")
        return 0

    if args.update:
        new = build_baseline(files, folders)
        old = load_baseline(args.baseline)
        if old is not None and not args.force:
            bad = increases({"files": old[0], "folders": old[1]}, new)
            if bad:
                print("Refusing to raise the baseline (baselines only decrease):")
                for b in bad:
                    print("  " + b)
                print("Fix the code, or pass --force with owner approval.")
                return 1
        args.baseline.parent.mkdir(parents=True, exist_ok=True)
        args.baseline.write_text(json.dumps(new, indent=2) + "\n")
        print(f"Baseline written: {len(new['files'])} files over {HARD_LIMIT}, "
              f"{len(new['folders'])} folders over {FOLDER_LIMIT}.")
        return 0

    base = load_baseline(args.baseline)
    if base is None:
        print(f"No baseline at {args.baseline}; run with --update to create it.")
        return 1
    errors, warnings, stale = check(files, folders, *base)
    if args.verbose:
        for w in warnings:
            print("warning:", w)
    for s in stale:
        print(f"note: {s} is now within limits; run --update to drop it from the baseline")
    if errors:
        print("File size guard failed:")
        for e in errors:
            print("  " + e)
        print("Split the file/folder instead of growing it (see scripts/README.md).")
        return 1
    print(f"file-size OK ({len(files)} files scanned, {len(warnings)} files over {WARN_LIMIT} lines, use -v to list)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
