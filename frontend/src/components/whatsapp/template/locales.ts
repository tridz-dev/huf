export function localeLabel(code: string): string {
  return TEMPLATE_LOCALES.find((l) => l.code === code)?.label ?? code;
}

export function isKnownLocale(code: string): boolean {
  return TEMPLATE_LOCALES.some((l) => l.code === code);
}
